import { argon2idAsync } from "@noble/hashes/argon2.js";
import { Buffer } from "node:buffer";
import { randomBytes, timingSafeEqual } from "node:crypto";

/**
 * Pure-JavaScript Argon2id works in Workers without native Node addons.
 * Keep the original parameters and PHC encoding so existing accounts work.
 */
const HASH_OPTIONS = {
  m: 19456, // 19 MiB
  t: 2,
  p: 1,
  dkLen: 32,
};

export async function hashPassword(plainTextPassword: string): Promise<string> {
  const salt = randomBytes(16);
  const hash = await argon2idAsync(plainTextPassword, salt, HASH_OPTIONS);
  return `$argon2id$v=19$m=19456,t=2,p=1$${salt.toString("base64").replace(/=+$/, "")}$${Buffer.from(hash).toString("base64").replace(/=+$/, "")}`;
}

export async function verifyPassword(
  storedHash: string,
  candidatePassword: string,
): Promise<boolean> {
  try {
    // Only accept the profile generated by this app, bounding verification
    // memory/CPU even if a stored hash has been corrupted.
    const match =
      /^\$argon2id\$v=19\$m=19456,t=2,p=1\$([A-Za-z0-9+/]{22})\$([A-Za-z0-9+/]{43})$/.exec(
        storedHash,
      );
    if (!match) return false;
    const salt = Buffer.from(match[1], "base64");
    const expected = Buffer.from(match[2], "base64");
    if (
      salt.toString("base64").replace(/=+$/, "") !== match[1] ||
      expected.toString("base64").replace(/=+$/, "") !== match[2]
    ) {
      return false;
    }
    const actual = await argon2idAsync(candidatePassword, salt, HASH_OPTIONS);
    return timingSafeEqual(expected, actual);
  } catch {
    // Malformed hash or verification error — treat as invalid credentials
    // rather than leaking failure details.
    return false;
  }
}
